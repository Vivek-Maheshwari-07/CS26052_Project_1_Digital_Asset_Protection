"""Build the gate_eval manifest for the folder-per-category dataset layout.

    python -m eval.build_manifest --dataset ../dataset [--test-share 0.3]

Layout and naming (as collected):
    originals/       orig_<ID>__<CATEGORY>__<SOURCE>.<ext>
    classical/       orig_<ID>__classical_edit__<EDIT>.<ext>
    platform/        orig_<ID>__platform__<PLATFORM>...
    ai_edits/        orig_<ID>__ai_<light|medium|heavy>__<TOOL>__<DESCRIPTOR>.<ext>
    hard_negatives/  orig_<ID>__sibling__<DESCRIPTOR>.<ext>
    unrelated/       unrel_<ID>__...
    distractors/     dist_<NNNN>.<ext>          (registry only)

Writes into the dataset folder:
    manifest.csv            one row per suspect; `file` is relative to the dataset root
    originals.csv           original_id, category, group
    registry_exclude.txt    originals left out of the registry (and every suspect derived from them)
    REVIEW.md               every relabel / exclusion and why

Label corrections are made from the data itself, never by hand:
  * a "platform" or "sibling" file that is byte-identical to its original is relabelled `copy`
    (it is the original re-uploaded, so a Tier 1 match on it is correct, not a false claim);
  * originals above the app's decode limit (Pillow's 178.9 MP bomb guard) cannot be registered,
    so they and their derived suspects are excluded.
"""
import argparse
import csv
import hashlib
import os
import re
import sys
from collections import Counter

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".webp", ".bmp"}
APP_PIXEL_LIMIT = 2 * Image.MAX_IMAGE_PIXELS  # the app's Pillow raises DecompressionBombError above this
Image.MAX_IMAGE_PIXELS = None  # here we only read headers, including those of the over-limit files
FIELDS = ["file", "original_id", "relation", "category", "edit", "tool", "platform", "notes", "split"]

RE_ORIG = re.compile(r"^orig_(\d+)__(.+?)__(.+)\.\w+$")
RE_CLASSICAL = re.compile(r"^orig_(\d+)__classical_edit__(.+)\.\w+$")
RE_PLATFORM = re.compile(r"^orig_(\d+)__platform__([A-Za-z0-9]+)")
RE_AI = re.compile(r"^orig_(\d+)__ai_(light|medium|heavy)__([^_]+(?:_[^_]+)*?)__(.+)\.\w+$")
RE_SIBLING = re.compile(r"^orig_(\d+)__sibling__(.+)\.\w+$")
RE_UNREL = re.compile(r"^unrel_(\d+)__")


def images(folder):
    return sorted(f for f in os.listdir(folder) if os.path.splitext(f)[1].lower() in IMAGE_EXTS) if os.path.isdir(folder) else []


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--test-share", type=float, default=0.3,
                    help="share of originals (by ID hash) whose suspects form the held-out test split")
    args = ap.parse_args()
    root = args.dataset
    review = ["# Dataset review", "", "Generated by `eval/build_manifest.py`; nothing in the dataset was modified.", ""]

    # ---------------------------------------------------------------- originals
    originals, excluded, problems = {}, {}, []
    for f in images(os.path.join(root, "originals")):
        m = RE_ORIG.match(f)
        if not m:
            problems.append(f"originals/{f}: name does not match orig_<ID>__<CATEGORY>__<SOURCE>.<ext>")
            continue
        path = os.path.join(root, "originals", f)
        with Image.open(path) as im:
            px = im.size[0] * im.size[1]
        rec = {"id": m[1], "stem": os.path.splitext(f)[0], "category": m[2], "group": m[3].split(".")[0],
               "sha": sha(path), "file": f}
        if px > APP_PIXEL_LIMIT:
            excluded[m[1]] = (rec, f"{px / 1e6:.0f} MP exceeds the app's decode limit ({APP_PIXEL_LIMIT / 1e6:.1f} MP)")
        else:
            originals[m[1]] = rec

    def split_of(oid):  # deterministic, stable when originals are added
        return "test" if int(hashlib.md5(oid.encode()).hexdigest(), 16) % 1000 < args.test_share * 1000 else "dev"

    rows, relabels, dropped = [], [], []

    def add(folder, f, oid, relation, edit="", tool="", platform="", notes=""):
        if oid in excluded:
            dropped.append(f"{folder}/{f} (derived from excluded original {oid})")
            return
        if oid and oid not in originals:
            problems.append(f"{folder}/{f}: original {oid} not found")
            return
        cat = originals[oid]["category"] if oid else "unrelated"
        rows.append({"file": f"{folder}/{f}", "original_id": originals[oid]["stem"] if oid else "", "relation": relation,
                     "category": cat, "edit": edit, "tool": tool, "platform": platform, "notes": notes,
                     "split": split_of(oid) if oid else split_of(f)})

    for f in images(os.path.join(root, "classical")):
        m = RE_CLASSICAL.match(f)
        if m:
            add("classical", f, m[1], "classical", edit=m[2], tool="make_classical_set.py")
        else:
            problems.append(f"classical/{f}: unexpected name")

    for f in images(os.path.join(root, "platform")):
        m = RE_PLATFORM.match(f)
        if not m:
            problems.append(f"platform/{f}: unexpected name")
            continue
        oid, plat = m[1], m[2].lower()
        if oid in originals and sha(os.path.join(root, "platform", f)) == originals[oid]["sha"]:
            relabels.append(f"platform/{f}: byte-identical to its original -> `copy` (not a platform round-trip)")
            add("platform", f, oid, "copy", edit="byte_identical_reupload", platform=plat, notes="labelled platform; byte-identical")
        else:
            add("platform", f, oid, "platform", edit=f"{plat}_roundtrip", platform=plat)

    for f in images(os.path.join(root, "ai_edits")):
        m = RE_AI.match(f)
        if m:
            add("ai_edits", f, m[1], f"ai_{m[2]}", edit=m[4], tool=m[3])
        else:
            problems.append(f"ai_edits/{f}: unexpected name")

    for f in images(os.path.join(root, "hard_negatives")):
        m = RE_SIBLING.match(f)
        if not m:
            problems.append(f"hard_negatives/{f}: unexpected name")
            continue
        oid = m[1]
        if oid in originals and sha(os.path.join(root, "hard_negatives", f)) == originals[oid]["sha"]:
            relabels.append(f"hard_negatives/{f}: byte-identical to its original -> `copy` (it is not a sibling capture)")
            add("hard_negatives", f, oid, "copy", edit="byte_identical_reupload", notes="labelled sibling; byte-identical")
        else:
            add("hard_negatives", f, oid, "sibling", edit=m[2])

    for f in images(os.path.join(root, "unrelated")):
        if RE_UNREL.match(f):
            add("unrelated", f, "", "unrelated")
        else:
            problems.append(f"unrelated/{f}: unexpected name")

    # ---------------------------------------------------------------- distractors
    dist = images(os.path.join(root, "distractors"))
    seen, dup = {}, 0
    orig_shas = {o["sha"] for o in originals.values()}
    for f in dist:
        h = sha(os.path.join(root, "distractors", f))
        if h in seen or h in orig_shas:
            dup += 1
        seen.setdefault(h, f)

    # ---------------------------------------------------------------- write
    with open(os.path.join(root, "manifest.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)
    with open(os.path.join(root, "originals.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["original_id", "category", "group", "split"])
        for o in originals.values():
            w.writerow([o["stem"], o["category"], o["group"], split_of(o["id"])])
    with open(os.path.join(root, "registry_exclude.txt"), "w", encoding="utf-8") as fh:
        fh.write("# originals left out of the registry (one file name per line)\n")
        for rec, why in excluded.values():
            fh.write(f"{rec['file']}\n")

    counts = Counter(r["relation"] for r in rows)
    review += ["## Counts", "",
               f"- originals usable: {len(originals)}; excluded: {len(excluded)}",
               f"- distractors: {len(dist)} files, {len(dist) - dup} unique (duplicates and copies of originals are registered once)",
               f"- suspects: {len(rows)} — " + ", ".join(f"{k} {v}" for k, v in counts.most_common()),
               f"- split: dev {sum(r['split'] == 'dev' for r in rows)}, test {sum(r['split'] == 'test' for r in rows)} (by original, {args.test_share:.0%} of originals in test)", ""]
    review += ["## Excluded originals", ""] + [f"- `{rec['file']}`: {why}" for rec, why in excluded.values()] + [""]
    review += ["## Relabelled", ""] + [f"- {x}" for x in relabels] + ([""] if relabels else ["- none", ""])
    review += ["## Dropped suspects (derived from excluded originals)", ""] + [f"- {x}" for x in dropped] + [""]
    review += ["## Problems", ""] + ([f"- {x}" for x in problems] if problems else ["- none"]) + [""]
    with open(os.path.join(root, "REVIEW.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(review))
    print("\n".join(review))
    if problems:
        sys.exit(1)


if __name__ == "__main__":
    main()
